# Add crate table
for crate_dir in RUST/cnc-*/; do
  if [[ -f "$crate_dir/Cargo.toml" ]]; then
    crate_name=$(basename "$crate_dir")
    description=$(grep '^description' "$crate_dir/Cargo.toml" | head -1 | sed 's/.*= *//; s/"//g')
