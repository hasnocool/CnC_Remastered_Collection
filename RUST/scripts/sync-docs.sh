#!/usr/bin/env bash
# sync-docs.sh - Automated documentation synchronization for RUST workspace
# Regenerates: file.tree, BUILD_STATUS.md, root codemap.md
# Usage: ./sync-docs.sh [--ci]  (--ci skips interactive prompts)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUST_DIR="$(dirname "$SCRIPT_DIR")"
ROOT_DIR="$(dirname "$RUST_DIR")"
CI_MODE="${1:-}"

echo "🔄 Syncing documentation..."

# 1. Generate file.tree using fd (from project root)
echo "📁 Generating file.tree..."
cd "$ROOT_DIR"
fd --type f --hidden --exclude .git --exclude target --exclude node_modules --exclude .graphflow --exclude .graphflow-cache --exclude graphflow-out --exclude backup --exclude .omo --exclude .slim | sort > file.tree.new
mv file.tree.new file.tree
echo "✅ file.tree updated ($(wc -l < file.tree) entries)"

# 2. Update BUILD_STATUS.md from cargo test results (from RUST dir)
echo "📊 Updating BUILD_STATUS.md..."
cd "$RUST_DIR"
TIMESTAMP=$(date -u +"%Y-%m-%d %H:%M:%S UTC")
RUST_VERSION=$(rustc --version 2>/dev/null || echo "unknown")
CARGO_VERSION=$(cargo --version 2>/dev/null || echo "unknown")

TEST_OUTPUT=$(cargo test --workspace 2>&1 || true)
PASSED=$(echo "$TEST_OUTPUT" | grep -oP "\d+ passed" | head -1 | grep -oP "\d+" || echo "0")
FAILED=$(echo "$TEST_OUTPUT" | grep -oP "\d+ failed" | head -1 | grep -oP "\d+" || echo "0")

cat > BUILD_STATUS.md.new << BUILD_EOF
# Build Status

_Last verified: $TIMESTAMP (cargo $CARGO_VERSION / rustc $RUST_VERSION)._

## Verification

```
cargo check --workspace --all-targets   # clean (warnings only)
cargo test --workspace                  # $PASSED passed, $FAILED failed
```

Per-target tests:

| Target | Tests |
|---|---|
BUILD_EOF

for crate_dir in cnc-*/; do
  if [[ -f "$crate_dir/Cargo.toml" ]]; then
    crate_name=$(basename "$crate_dir")
    crate_output=$(cargo test --package "$crate_name" 2>&1 || true)
    crate_passed=$(echo "$crate_output" | grep -oP "\d+ passed" | head -1 | grep -oP "\d+" || echo "0")
    crate_failed=$(echo "$crate_output" | grep -oP "\d+ failed" | head -1 | grep -oP "\d+" || echo "0")
    if [[ "$crate_passed" != "0" || "$crate_failed" != "0" ]]; then
      echo "| $crate_name | $crate_passed passed, $crate_failed failed |" >> BUILD_STATUS.md.new
    fi
  fi
done

cat >> BUILD_STATUS.md.new << BUILD_EOF

---

## Crate Health Matrix

| Crate | Version | README | CHANGELOG | codemap | Tests |
|---|---|---|---|---|---|
BUILD_EOF

for crate_dir in cnc-*/; do
  if [[ -f "$crate_dir/Cargo.toml" ]]; then
    crate_name=$(basename "$crate_dir")
    version_raw=$(grep '^version' "$crate_dir/Cargo.toml" | head -1 | sed 's/.*= *//; s/["{}]//g')
    if [[ "$version_raw" == *"workspace"* ]]; then
      version="workspace"
    else
      version="$version_raw"
    fi
    readme=$([[ -f "$crate_dir/README.md" ]] && echo "✅" || echo "❌")
    changelog=$([[ -f "$crate_dir/CHANGELOG.md" ]] && echo "✅" || echo "❌")
    codemap=$([[ -f "$crate_dir/codemap.md" ]] && echo "✅" || echo "❌")
    crate_output=$(cargo test --package "$crate_name" 2>&1 || true)
    crate_passed=$(echo "$crate_output" | grep -oP "\d+ passed" | head -1 | grep -oP "\d+" || echo "0")
    crate_failed=$(echo "$crate_output" | grep -oP "\d+ failed" | head -1 | grep -oP "\d+" || echo "0")
    tests="${crate_passed}✅/${crate_failed}❌"
    echo "| $crate_name | $version | $readme | $changelog | $codemap | $tests |" >> BUILD_STATUS.md.new
  fi
done

cat >> BUILD_STATUS.md.new << BUILD_EOF

---

## Cargo Check

```
cargo check --workspace --all-targets
```

---

## Clippy

```
cargo clippy --workspace -- -D warnings
```

---

## Formatting

```
cargo fmt --all -- --check
```

---

*Auto-generated by sync-docs.sh on $TIMESTAMP*
BUILD_EOF

mv BUILD_STATUS.md.new BUILD_STATUS.md
echo "✅ BUILD_STATUS.md updated"

# 3. Update root codemap.md
echo "🗺️  Updating root codemap.md..."
cd "$ROOT_DIR"

cat > codemap.md.new << 'CODEMAP_EOF'
