pub struct OriginalTemplate {
    /// INI name as used in scenario files (e.g. `"SH1"`).
    pub name: &'static str,
    /// Icon width in cells.
    pub width: u8,
    /// Icon height in cells.
    pub height: u8,
    /// Ground type of the default icons.
    pub land: LandType,
    /// Ground type of the alternate icons.
    pub alt_land: LandType,
    /// Icon indices (`row * width + col`) whose ground is [`Self::alt_land`].
    pub alt_icons: &'static [u16],
    /// Theater bitmask: bit 0 = Temperate, bit 1 = Snow, bit 2 = Interior.
    pub theater_mask: u16,
    /// The C# `ID` as string (e.g. "Clear", "Shore01", "Wall0001").
    pub fullname: &'static str,
}

