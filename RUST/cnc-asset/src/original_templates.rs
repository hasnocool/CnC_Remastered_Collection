/// Return the template table for the given game.
pub fn templates_for(game: crate::original_assets::Game) -> &'static [OriginalTemplate] {
    match game {
        crate::original_assets::Game::TiberianDawn => ORIGINAL_TEMPLATES,
        crate::original_assets::Game::RedAlert => RA_TEMPLATES,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_complete() {
        // The original TD game defines 216 templates.
        let unique: std::collections::HashSet<_> =
            ORIGINAL_TEMPLATES.iter().map(|t| t.name).collect();
        assert_eq!(unique.len(), ORIGINAL_TEMPLATES.len(), "duplicate names");
        assert_eq!(ORIGINAL_TEMPLATES.len(), 216);
    }

    #[test]
    fn ra_table_is_complete() {
        // Red Alert defines 401 templates.
        let unique: std::collections::HashSet<_> = RA_TEMPLATES.iter().map(|t| t.name).collect();
        assert_eq!(unique.len(), RA_TEMPLATES.len(), "duplicate names");
        assert_eq!(RA_TEMPLATES.len(), 401);
    }

    #[test]
    fn shore_templates_use_beach_alt() {
        // SH1 is the canonical shoreline: water ground, beach alt icons.
        let sh1 = ORIGINAL_TEMPLATES.iter().find(|t| t.name == "SH1").unwrap();
        assert_eq!(sh1.land, LandType::Water);
        assert_eq!(sh1.alt_land, LandType::Beach);
        assert_eq!((sh1.width, sh1.height), (3, 3));
        // The original source's slope111111 list marks icons 0..6 as beach.
        assert_eq!(sh1.alt_icons, &[0, 1, 2, 3, 4, 5]);
    }

    #[test]
    fn slopes_use_clear_alt() {
        // S01-S38 are rock slopes: rock ground with clear-alt icons.
        let s01 = ORIGINAL_TEMPLATES.iter().find(|t| t.name == "S01").unwrap();
        assert_eq!(s01.land, LandType::Rock);
        assert_eq!(s01.alt_land, LandType::Clear);
        assert_eq!((s01.width, s01.height), (2, 2));
    }

    #[test]
    fn water_is_pure() {
        // W1/W2 have no alternate icons: entirely water.
        for name in ["W1", "W2"] {
            let w = ORIGINAL_TEMPLATES.iter().find(|t| t.name == name).unwrap();
            assert_eq!(w.land, LandType::Water);
            assert_eq!(w.alt_land, LandType::Water);
            assert!(w.alt_icons.is_empty(), "{name} must have no alt icons");
        }
    }

    #[test]
    fn land_parse_roundtrip() {
        for s in [
            "CLEAR", "ROCK", "WATER", "BEACH", "ROAD", "TIBERIUM", "WALL", "ROUGH", "RIVER",
        ] {
            assert_eq!(LandType::parse(s), LandType::parse(s));
        }
        assert_eq!(LandType::parse("BOGUS"), LandType::Clear);
    }

    #[test]
    fn templates_for_td() {
        let td = templates_for(crate::original_assets::Game::TiberianDawn);
        assert_eq!(td.len(), 216);
        assert_eq!(td[0].name, "B1");
    }

    #[test]
    fn templates_for_ra() {
        let ra = templates_for(crate::original_assets::Game::RedAlert);
        assert_eq!(ra.len(), 401);
        assert_eq!(ra[0].name, "clear1");
    }

    #[test]
    fn alt_icons_in_bounds() {
        for t in ORIGINAL_TEMPLATES {
            let max = (t.width * t.height) as u16;
            for &idx in t.alt_icons {
                assert!(
                    idx < max,
                    "{} alt_icon {} out of bounds (max {})",
                    t.name,
                    idx,
                    max
                );
            }
        }
        for t in RA_TEMPLATES {
            let max = (t.width * t.height) as u16;
            for &idx in t.alt_icons {
                assert!(
                    idx < max,
                    "{} alt_icon {} out of bounds (max {})",
                    t.name,
                    idx,
                    max
                );
            }
        }
    }
}
