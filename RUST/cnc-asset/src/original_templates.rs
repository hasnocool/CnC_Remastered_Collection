//! Original C&C (Tiberian Dawn) template table, extracted from the shipped
//! game source (`original/TIBERIANDAWN/CDATA.CPP`).
//!
//! Every terrain tile in the original game is an icon inside a named template
//! set (e.g. `SH1` = shore template 1, 3x3 icons). A template declares:
//!
//! - the icon width/height in cells,
//! - the default [`LandType`] for its icons,
//! - an alternate land type plus a list of icon indices that use it - this is
//!   how the original encodes shorelines (water template, beach alt icons) and
//!   rock slopes (rock template, clear alt icons).
//!
//! The map editor and launcher use this table to pick the same tiles the
//! original engine would pick for a given terrain type, and to know which
//! ground a given icon contributes for game logic (movement, buildability).

// Generated from original/TIBERIANDAWN/CDATA.CPP TemplateTypeClass table.
// One entry per original template: INI name, icon WxH, land type, alt land,
// and the AltIcons list (which icons of the set use the ALT land type).

/// Ground classification of a template icon, mirroring the original `LandType`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum LandType {
    Clear,
    Rock,
    Water,
    Beach,
    Road,
    Tiberium,
    Wall,
    Rough,
    River,
}

impl LandType {
    /// Parse the C++ source spelling (`LAND_CLEAR`, `LAND_ROCK`, ...).
    pub fn parse(s: &str) -> Self {
        match s {
            "CLEAR" => Self::Clear,
            "ROCK" => Self::Rock,
            "WATER" => Self::Water,
            "BEACH" => Self::Beach,
            "ROAD" => Self::Road,
            "TIBERIUM" => Self::Tiberium,
            "WALL" => Self::Wall,
            "ROUGH" => Self::Rough,
            "RIVER" => Self::River,
            _ => Self::Clear,
        }
    }
}

/// One original template set: name, icon grid, ground types.
