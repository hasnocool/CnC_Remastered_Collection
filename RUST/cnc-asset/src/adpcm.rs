//! Westwood SOS ADPCM decoder.
//!
//! This is the ADPCM codec the Westwood engines ship: the algorithm and the
//! two lookup tables are taken **verbatim from the original game source that
//! lives in this repository**:
//!
//! * `REDALERT/ADPCM.CPP` — `sosCODECDecompressData()` (the decode loop),
//! * `REDALERT/ITABLE.CPP` — `IndexTable[]` (next quantiser row),
//! * `REDALERT/DTABLE.CPP` — `DiffTable[]` (signed step per row/token pair),
//! * `REDALERT/WIN32LIB/SOSCOMP.H` — `_SOS_COMPRESS_INFO` (the per-channel
//!   state: sample index + predicted sample, duplicated for channel 2).
//!
//! Because the tables are byte-for-byte the originals, a stream decoded here
//! matches what the game would have played.
//!
//! # Algorithm (mirrors `REDALERT/ADPCM.CPP`)
//!
//! One input byte carries two 4-bit ADPCM codes. The low nibble is decoded
//! first, the high nibble second. The decoder keeps a *table offset*
//! (`index`) into the 89 x 16 tables; `IndexTable` maps that offset to the
//! next row's offset and `DiffTable` gives the signed step:
//!
//! ```text
//! offset += token & 0x0F;
//! sample += DIFF_TABLE[offset];
//! offset  = INDEX_TABLE[offset];
//! sample  = clamp(sample, -32768, 32767);
//! emit(sample);
//! ```
//!
//! # Stereo
//!
//! `_SOS_COMPRESS_INFO` carries a second complete decoder state for channel
//! 2, so Westwood's own codec is a multi-channel codec. This module models
//! that as byte-interleaving: even input bytes feed channel 0, odd input
//! bytes feed channel 1, and each channel keeps its own state.

use thiserror::Error;

/// Failures of the Westwood ADPCM decoder.
#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum AdpcmError {
    /// The quantiser offset left the table. Cannot happen for a well-formed
    /// stream; kept so a corrupted table build degrades to an error instead
    /// of a panic.
    #[error("ADPCM quantiser offset {offset} is outside the {len}-entry table")]
    IndexOutOfRange { offset: usize, len: usize },
}

/// Per-channel Westwood ADPCM decoder state.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Decoder {
    /// Table offset of the current quantiser row (always a multiple of 16).
    offset: u32,
    /// Running predicted sample, clamped to the i16 range after every step.
    predicted: i32,
}

impl Decoder {
    /// A fresh decoder: quantiser row 0, predicted sample 0 — exactly what
    /// `sosCODECInitStream()` sets up.
    pub fn new() -> Self {
        Self::default()
    }

    /// Decode one input byte into two samples (low nibble first, then high).
    pub fn decode_byte(&mut self, token: u8) -> Result<[i16; 2], AdpcmError> {
        let low = self.decode_nibble(token & 0x0F)?;
        let high = self.decode_nibble(token >> 4)?;
        Ok([low, high])
    }

    /// Decode a whole stream, appending the samples to `out`.
    pub fn decode_into(&mut self, input: &[u8], out: &mut Vec<i16>) -> Result<(), AdpcmError> {
        out.reserve(input.len() * 2);
        for &token in input {
            let [low, high] = self.decode_byte(token)?;
            out.push(low);
            out.push(high);
        }
        Ok(())
    }

    /// Decode a whole mono stream into a fresh vector.
    pub fn decode(input: &[u8]) -> Result<Vec<i16>, AdpcmError> {
        let mut decoder = Decoder::new();
        let mut out = Vec::with_capacity(input.len() * 2);
        decoder.decode_into(input, &mut out)?;
        Ok(out)
    }

    fn decode_nibble(&mut self, token: u8) -> Result<i16, AdpcmError> {
        self.offset += u32::from(token);
        let slot = self.offset as usize;
        let step = *DIFF_TABLE.get(slot).ok_or(AdpcmError::IndexOutOfRange {
            offset: slot,
            len: DIFF_TABLE.len(),
        })?;
        let next = *INDEX_TABLE.get(slot).ok_or(AdpcmError::IndexOutOfRange {
            offset: slot,
            len: INDEX_TABLE.len(),
        })?;
        self.offset = u32::from(next);
        self.predicted = (self.predicted + step).clamp(-32768, 32767);
        Ok(self.predicted as i16)
    }
}

/// Decode a stereo Westwood ADPCM stream.
///
/// Even input bytes feed the left channel, odd input bytes feed the right
/// channel; each channel keeps its own quantiser state, matching the
/// dual-state `_SOS_COMPRESS_INFO` of the original codec. The two channels
/// always produce the same number of samples: a trailing odd byte is
/// decoded for the left channel only and the right channel ends one sample
/// earlier.
pub fn decode_stereo(input: &[u8]) -> Result<(Vec<i16>, Vec<i16>), AdpcmError> {
    let mut left = Decoder::new();
    let mut right = Decoder::new();
    let mut left_samples = Vec::with_capacity(input.len());
    let mut right_samples = Vec::with_capacity(input.len());
    for (index, &token) in input.iter().enumerate() {
        if index % 2 == 0 {
            let [low, high] = left.decode_byte(token)?;
            left_samples.push(low);
            left_samples.push(high);
        } else {
            let [low, high] = right.decode_byte(token)?;
            right_samples.push(low);
            right_samples.push(high);
        }
    }
    Ok((left_samples, right_samples))
}

